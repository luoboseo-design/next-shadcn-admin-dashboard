export interface PlatformAccount {
  id: string;
  platform: PlatformType;
  platformName: string;
  username: string;
  /** 平台登录密码（脱敏展示） */
  password: string;
  /** 账号来源 */
  source: AccountSource;
  /** 关联的邮箱池条目 id（来自身份资源） */
  emailId: string;
  email: string;
  /** 绑定的代理条目 id */
  proxyId: string;
  health: AccountHealth;
  /** 账龄天数，反映养号成熟度 */
  ageDays: number;
  /** 每日发布上限 */
  dailyLimit: number;
  /** 今日已使用 */
  usedToday: number;
  /** 累计发布数 */
  totalPublished: number;
  lastUsed: string | null;
}

